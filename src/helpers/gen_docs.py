"""Generate the agent-facing helper docs from docstrings (part 09 §4).

Reads the docstrings of ``masks_io``, ``tracks``, ``physics``,
``clock`` and ``ranges`` and writes ``src/helpers/HELPERS_DOCS.md``
(marked do-not-edit). The prompt therefore never describes a helper that does
not exist or a signature that changed: regenerating docs and getting a
diff fails the build (wired in part 15).

Usage, from the repo root::

    uv run --python 3.13 python -m src.helpers.gen_docs       # rewrite
    uv run --python 3.13 python -m src.helpers.gen_docs --check  # diff only

Parsing is done with :mod:`ast` so generation never imports the
runtime (and never executes helper code).
"""

from __future__ import annotations

import ast
import difflib
import sys
from pathlib import Path

__all__ = ["docs_path", "generate_docs", "main"]

#: Modules documented, in the order they appear in the brief.
MODULES = ("masks_io", "tracks", "physics", "clock", "ranges")

#: Marker proving the file is generated (the build checks for it).
GENERATED_MARKER = "<!-- do-not-edit: generated by src/helpers/gen_docs.py -->"


def docs_path() -> Path:
    """Absolute path of the generated ``HELPERS_DOCS.md``."""
    return Path(__file__).resolve().parent / "HELPERS_DOCS.md"


def _signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """The ``def ...`` header reconstructed from the AST."""
    parts = []
    args = node.args
    positional = list(args.posonlyargs) + list(args.args)
    defaults = [None] * (len(positional) - len(args.defaults)) + list(
        args.defaults)
    for arg, default in zip(positional, defaults):
        text = arg.arg
        if arg.annotation is not None:
            text += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            text += f" = {ast.unparse(default)}"
        parts.append(text)
    if args.vararg is not None:
        parts.append(f"*{args.vararg.arg}")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        text = arg.arg
        if arg.annotation is not None:
            text += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            text += f" = {ast.unparse(default)}"
        parts.append(text)
    if args.kwarg is not None:
        parts.append(f"**{args.kwarg.arg}")
    returns = ""
    if node.returns is not None:
        returns = f" -> {ast.unparse(node.returns)}"
    prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    return f"{prefix} {node.name}({', '.join(parts)}){returns}"


def _module_public(path: Path):
    """``(docstring, [(name, signature, docstring)])`` for one module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    module_doc = ast.get_docstring(tree) or ""
    exported = None
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if (isinstance(target, ast.Name)
                        and target.id == "__all__"):
                    try:
                        exported = list(ast.literal_eval(node.value))
                    except (ValueError, SyntaxError):
                        exported = None
    functions = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith("_"):
                continue
            if exported is not None and node.name not in exported:
                continue
            functions.append((node.name, _signature(node),
                              ast.get_docstring(node) or ""))
    return module_doc, functions


def generate_docs() -> str:
    """Render ``HELPERS_DOCS.md`` from the helpers' own docstrings."""
    here = Path(__file__).resolve().parent
    lines = [GENERATED_MARKER, "# Helper library (generated)",
             "",
             "Do-not-edit: generated from the docstrings in "
             "`src/helpers/` by `src/helpers/gen_docs.py`. "
             "Regenerating and getting a diff fails the build.",
             ""]
    for module in MODULES:
        module_doc, functions = _module_public(here / f"{module}.py")
        lines.append(f"## {module}")
        lines.append("")
        if module_doc:
            lines.append(module_doc)
            lines.append("")
        for name, signature, doc in functions:
            lines.append(f"### `{module}.{name}`")
            lines.append("")
            lines.append("```python")
            lines.append(signature)
            lines.append("```")
            lines.append("")
            lines.append(doc if doc else "(no docstring)")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None) -> int:
    """Rewrite the docs, or ``--check`` that they are current."""
    args = list(sys.argv[1:] if argv is None else argv)
    wanted = generate_docs()
    target = docs_path()
    if "--check" in args:
        try:
            current = target.read_text(encoding="utf-8")
        except OSError:
            print(f"gen_docs: {target} is missing", flush=True)
            return 1
        if current != wanted:
            diff = difflib.unified_diff(
                current.splitlines(), wanted.splitlines(),
                str(target), "regenerated", lineterm="")
            print("\n".join(list(diff)[:40]), flush=True)
            print("gen_docs: HELPERS_DOCS.md differs from the "
                  "docstrings; regenerate it", flush=True)
            return 1
        print("gen_docs: HELPERS_DOCS.md is current", flush=True)
        return 0
    target.write_text(wanted, encoding="utf-8")
    print(f"gen_docs: wrote {target}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
